"""Open every saved model and summarise what it learned -> results/00_overview/model_cards.md"""
import json
import os
import sys

import joblib
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from pathsnap.features import FEATURES

ORDER = ["logreg", "gnb", "knn", "dtree", "rf", "extratrees", "histgb", "lightgbm", "mlp", "final"]
runs = json.load(open("results/03_concurrent_training/model_runs.json"))
final_meta = json.load(open("models/final_model.json"))
out = ["# Model cards\n", "Generated by `scripts/07_model_cards.py` from the saved files in `models/`.\n"]


def top(names, vals, k=5, absval=False):
    v = np.abs(vals) if absval else vals
    o = np.argsort(-v)[:k]
    return ", ".join(f"{names[i]} ({vals[i]:+.3f})" if absval else f"{names[i]} ({vals[i]:.3f})" for i in o)


for name in ORDER:
    path = f"models/{name}.joblib"
    m = joblib.load(path)
    est = m[-1] if hasattr(m, "steps") else m
    lines = [f"## {name}", f"- file: `{path}` ({os.path.getsize(path) / 1e6:.2f} MB)",
             f"- object: `{type(m).__name__}`" + (f" = {' → '.join(type(s).__name__ for _, s in m.steps)}" if hasattr(m, 'steps') else "")]
    keys = {"LogisticRegression": ["C", "solver", "max_iter"], "GaussianNB": ["var_smoothing"],
            "KNeighborsClassifier": ["n_neighbors", "weights", "metric", "algorithm"],
            "DecisionTreeClassifier": ["max_depth", "min_samples_leaf", "criterion"],
            "RandomForestClassifier": ["n_estimators", "max_depth", "min_samples_leaf", "max_features"],
            "ExtraTreesClassifier": ["n_estimators", "max_depth", "min_samples_leaf", "max_features"],
            "HistGradientBoostingClassifier": ["max_iter", "learning_rate", "max_leaf_nodes", "early_stopping"],
            "LGBMClassifier": ["n_estimators", "learning_rate", "num_leaves", "min_child_samples", "subsample", "colsample_bytree", "reg_lambda"],
            "MLPClassifier": ["hidden_layer_sizes", "activation", "solver", "alpha", "early_stopping"]}
    p = est.get_params()
    lines.append("- hyperparameters: " + ", ".join(f"{k}={p[k]!r}" if not isinstance(p[k], float) else f"{k}={p[k]:.4g}"
                                                 for k in keys.get(type(est).__name__, []) if k in p))
    t = type(est).__name__
    if t == "LogisticRegression":
        lines.append(f"- learned: intercept {est.intercept_[0]:+.3f}; largest |coefficients| (standardised features): "
                     + top(FEATURES, est.coef_[0], absval=True))
    elif t == "GaussianNB":
        d = (est.theta_[1] - est.theta_[0]) / np.sqrt(est.var_.mean(0))
        lines.append(f"- learned: class priors {np.round(est.class_prior_, 3).tolist()}; features whose class means differ most "
                     "(standardised mean difference, true − false): " + top(FEATURES, d, absval=True))
    elif t == "KNeighborsClassifier":
        lines.append(f"- learned: stores {est.n_samples_fit_} training rows (no parameters fitted); "
                     "predicts by a distance-weighted vote of the 25 nearest rows")
    elif t == "DecisionTreeClassifier":
        lines.append(f"- learned: depth {est.get_depth()}, {est.get_n_leaves()} leaves; root split on "
                     f"`{FEATURES[est.tree_.feature[0]]}` ≤ {est.tree_.threshold[0]:.3f}")
        lines.append("- top feature importances: " + top(FEATURES, est.feature_importances_))
    elif t in ("RandomForestClassifier", "ExtraTreesClassifier"):
        depths = [e.get_depth() for e in est.estimators_]
        leaves = [e.get_n_leaves() for e in est.estimators_]
        lines.append(f"- learned: {len(est.estimators_)} trees, mean depth {np.mean(depths):.1f}, mean leaves {np.mean(leaves):.0f}")
        lines.append("- top feature importances: " + top(FEATURES, est.feature_importances_))
    elif t == "HistGradientBoostingClassifier":
        lines.append(f"- learned: {est.n_iter_} boosting iterations")
    elif t == "LGBMClassifier":
        b = est.booster_
        gain = b.feature_importance("gain"); gain = gain / gain.sum()
        lines.append(f"- learned: {b.num_trees()} trees")
        lines.append("- top feature importances (share of total split gain): " + top(FEATURES, gain))
    elif t == "MLPClassifier":
        shapes = [w.shape for w in est.coefs_]
        n = sum(w.size for w in est.coefs_) + sum(b.size for b in est.intercepts_)
        lines.append(f"- learned: layers {' → '.join(str(s[0]) for s in shapes)} → {shapes[-1][1]}, {n} weights; "
                     f"stopped after {est.n_iter_} epochs (early stopping), final training loss {est.loss_:.4f}, "
                     f"best validation accuracy {max(est.validation_scores_):.4f}")
    r = runs.get(name)
    if name == "final":
        lines.append(f"- role: **deployed model** (LightGBM after Bayesian optimisation, {final_meta['trials']} trials)")
        r = None
        import pandas as pd
        tv = pd.read_csv("results/04_bayesian_optimisation/tuned_vs_untuned.csv").set_index("variant").loc["tuned"]
        lines.append(f"- results: CV macro F1 {tv.cv_macro_f1:.4f} | student-test Top-1 {tv.test_top1:.4f}, "
                     f"macro F1 {tv.test_macro_f1:.4f}, log loss {tv.test_log_loss:.4f}")
    if r:
        tt = r["student_test"]
        cv = np.mean([f["macro_f1"] for f in r["cv_folds"]])
        lines.append(f"- results: CV macro F1 {cv:.4f} | student-test Top-1 {tt['top1']:.4f}, macro F1 {tt['macro_f1']:.4f}, "
                     f"log loss {tt['log_loss']:.4f}")
    out.append("\n".join(lines) + "\n")

open("results/00_overview/model_cards.md", "w").write("\n".join(out))
print("\n".join(out))
